    /// Groups for the slot menus, in SDK order.
    static let groups: [(name: String, waves: [String])] = {
        func group(_ n: String) -> String {
            if n.hasPrefix("TRANSITION_RAMP_UP") { return "Ramp up" }
            if n.hasPrefix("TRANSITION_RAMP_DOWN") { return "Ramp down" }
            if n.hasPrefix("TRANSITION") { return "Transition" }
            if n.contains("DOUBLE") || n.contains("TRIPLE") { return "Double / triple" }
            if n.contains("BUZZ") || n.hasPrefix("ALERT") || n.contains("FUZZ") { return "Buzz / alert" }
            if n.hasPrefix("PULSING") { return "Pulsing" }
            if n.contains("HUM") { return "Hum" }
            return "Click / tick / bump"
        }
        var order: [String] = []
        var map: [String: [String]] = [:]
        for n in all {
            let g = group(n)
            if map[g] == nil { order.append(g) }
            map[g, default: []].append(n)
        }
        return order.map { ($0, map[$0]!) }
    }()

    /// Short label for a slot button, e.g. BUZZ1_P100 -> "buzz1 100".
    static func short(_ n: String) -> String {
        n.replacingOccurrences(of: "TRANSITION_", with: "")
            .replacingOccurrences(of: "_P", with: " ")
            .replacingOccurrences(of: "_", with: " ")
            .lowercased()
    }
